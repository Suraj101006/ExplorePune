async function seed() {
  console.log('Seeding categories...');
  for (const cat of CATEGORIES) {
    await setDoc(doc(db, 'place_categories', cat.slug), cat);
  }
  console.log(`✓ ${CATEGORIES.length} categories seeded.`);

  console.log('Seeding milestones...');
  for (const m of MILESTONES) {
    await setDoc(doc(db, 'milestones', m.id), m);
  }
  console.log(`✓ ${MILESTONES.length} milestones seeded.`);

  console.log('Seeding curated Pune places...');
  for (const place of CURATED_PLACES) {
    await setDoc(doc(db, 'places', place.slug), place);
  }
  console.log(`✓ ${CURATED_PLACES.length} curated places seeded.`);

  // Load additional elements from OSM JSON if available
  const osmPath = path.resolve('data/raw/osm-pune-core.json');
  if (fs.existsSync(osmPath)) {
    try {
      const raw = JSON.parse(fs.readFileSync(osmPath, 'utf8'));
      const elements = (raw.elements || []).filter((e) => e.tags && e.tags.name && e.lat && e.lon);
      console.log(`Found ${elements.length} named OSM elements.`);
      let count = 0;
      for (const el of elements.slice(0, 50)) {
        const name = el.tags.name;
        const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || `osm-${el.id}`;
        // Skip if already in curated places
        if (CURATED_PLACES.some((p) => p.slug === slug)) continue;

        let catSlug = 'heritage';
        if (el.tags.historic === 'castle' || el.tags.historic === 'fort') catSlug = 'forts';
        else if (el.tags.amenity === 'place_of_worship') catSlug = 'temples';
        else if (el.tags.tourism === 'museum') catSlug = 'museums';
        else if (el.tags.leisure === 'park') catSlug = 'parks';
        else if (el.tags.tourism === 'viewpoint') catSlug = 'nature';

        const placeDoc = {
          id: slug,
          slug,
          name,
          name_mr: el.tags['name:mr'] || null,
          description: el.tags.description || `Historic point of interest in Pune listed in OpenStreetMap records.`,
          address: el.tags['addr:street'] ? `${el.tags['addr:street']}, Pune` : 'Pune, Maharashtra',
          latitude: el.lat,
          longitude: el.lon,
          zone: (Math.abs(el.lat - 18.52) > 0.1 || Math.abs(el.lon - 73.85) > 0.1) ? 'day_trip' : 'city',
          data_tier: 'listed',
          status: 'published',
          popularity_score: 60,
          recommended_duration_minutes: 45,
          place_categories: [{ name: CATEGORIES.find((c) => c.slug === catSlug)?.name || 'Attraction', slug: catSlug }],
          category_slug: catSlug,
          category: catSlug,
          place_prices: [{ visitor_category: 'General', amount: 0, is_free: true }],
          created_at: new Date().toISOString(),
        };

        await setDoc(doc(db, 'places', slug), placeDoc);
        count++;
      }
      console.log(`✓ Added ${count} additional places from OSM.`);
    } catch (e) {
      console.warn('Could not parse OSM file:', e.message);
    }
  }

  console.log('🎉 Seeding successfully completed!');
  process.exit(0);
}

seed().catch((err) => {
  console.error('Seeding failed:', err);
  process.exit(1);
});
